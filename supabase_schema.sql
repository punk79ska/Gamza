-- ============================================================================
-- Gamza Market Database Schema (Supabase PostgreSQL)
-- Privacy-Preserving: No PII (No real names, emails, or phone numbers)
-- ============================================================================

-- 1. User Profiles (비식별 판매자/사용자 프로필)
CREATE TABLE IF NOT EXISTS public.user_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nickname VARCHAR(30) NOT NULL UNIQUE,
    profile_img TEXT,
    activity_location VARCHAR(50) NOT NULL DEFAULT '역삼1동',
    potato_temp NUMERIC(4, 1) NOT NULL DEFAULT 36.5,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Products (중고 거래 상품)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id UUID NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    title VARCHAR(60) NOT NULL,
    category VARCHAR(30) NOT NULL,
    price INTEGER NOT NULL DEFAULT 0 CHECK (price >= 0),
    location VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT '판매중' CHECK (status IN ('판매중', '예약중', '거래 완료')),
    image_url TEXT NOT NULL,
    description TEXT NOT NULL,
    likes_count INTEGER NOT NULL DEFAULT 0 CHECK (likes_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. Product Likes (관심 상품 / 찜)
CREATE TABLE IF NOT EXISTS public.product_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT unique_product_user_like UNIQUE (product_id, user_id)
);

-- 4. Chat Rooms (1:1 대화방)
CREATE TABLE IF NOT EXISTS public.chat_rooms (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    buyer_id UUID NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    seller_id UUID NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT unique_chat_room_product_buyer UNIQUE (product_id, buyer_id)
);

-- 5. Chat Messages (대화 메시지)
CREATE TABLE IF NOT EXISTS public.chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id UUID NOT NULL REFERENCES public.chat_rooms(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ============================================================================
-- Performance Indexes
-- ============================================================================
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);
CREATE INDEX IF NOT EXISTS idx_products_status ON public.products(status);
CREATE INDEX IF NOT EXISTS idx_products_created_at ON public.products(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_likes_count ON public.products(likes_count DESC);
CREATE INDEX IF NOT EXISTS idx_products_price ON public.products(price ASC);
CREATE INDEX IF NOT EXISTS idx_chat_messages_room_created ON public.chat_messages(room_id, created_at ASC);

-- ============================================================================
